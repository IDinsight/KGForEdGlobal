@PARAM(argnames=("reverse_pair",), argvalues=[(False,), (True,)])
def test_lp_config_rejects_reverse_and_duplicate_unordered_pairs(
    reverse_pair: bool,
) -> None:
    """An unordered type pair cannot recur in the same or reverse field order.

    Parameters
    ----------
    reverse_pair
        Whether the duplicate swaps the two semantically unordered endpoints.
    """

    payload = _valid_lp_config()
    pairs = payload["relates_to"]["allowed_statement_type_pairs"]
    pairs[0] = {
        "first_statement_type": "Content Standard",
        "second_statement_type": "Indicator",
    }
    duplicate = deepcopy(pairs[0])
    if reverse_pair:
        duplicate = {
            "first_statement_type": "Indicator",
            "second_statement_type": "Content Standard",
        }
    pairs.append(duplicate)

    with pytest.raises(
        expected_exception=ValidationError,
        match="duplicate or reverse-duplicate unordered pairs",
    ):
        _CreateKGLearningProgressionsConfig.model_validate(payload)


