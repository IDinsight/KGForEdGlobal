def _assert_extra_field_rejected(
    *, field_name: str, path: tuple[str | int, ...], value: object
) -> None:
    """Assert that an extra LP configuration field fails at its actual location.

    Parameters
    ----------
    field_name
        Name of the unapproved runtime field.
    path
        Location of the model whose strict field boundary is under test.
    value
        Representative value for the unapproved field.
    """

    payload = _valid_lp_config()
    _nested_mapping(path=path, payload=payload)[field_name] = value

    with pytest.raises(expected_exception=ValidationError) as exc_info:
        _CreateKGLearningProgressionsConfig.model_validate(payload)

    assert any(
        error["loc"] == (*path, field_name) and error["type"] == "extra_forbidden"
        for error in exc_info.value.errors()
    )


def _nested_mapping(
    *, path: tuple[str | int, ...], payload: dict[str, Any]
) -> dict[str, Any]:
    """Return the nested mapping at one path in an LP configuration payload.

    Parameters
    ----------
    path
        String keys and list indexes leading to the target mapping.
    payload
        Complete mutable LP configuration payload.

    Returns
    -------
    dict[str, Any]
        Mutable mapping at the requested path.
    """

    current: Any = payload
    for part in path:
        current = current[part]

    assert isinstance(current, dict)
    return current


