def test_lp_config_accepts_integer_boundaries() -> None:
    """Positive controls accept one and retry controls accept zero."""

    payload = _valid_lp_config()
    for path, positive_only in _INTEGER_CONTROLS:
        parent = _nested_mapping(path=path[:-1], payload=payload)
        parent[path[-1]] = 1 if positive_only else 0

    parsed = _CreateKGLearningProgressionsConfig.model_validate(payload)

    assert parsed.request_batch_size == 1
    assert parsed.retry.checker_max_retries == 0
    assert parsed.retry.producer_max_retries == 0


