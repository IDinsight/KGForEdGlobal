def _assert_metadata(*, harness: _claims._Harness, rows: LPRelationships) -> None:
    """Compare ownership and every material reference with actual persisted inputs.

    Parameters
    ----------
    harness
        Authoritative synthetic inputs and offline adjudication directory.
    rows
        Minted rows under test, including embedded and separately keyed provenance.
    """
    root = harness.root
    final = LPFinalClaims.model_validate_json(
        (root / "lp_final_claims.json").read_bytes()
    )
    _claims._assert_provenance(artifact=final, root=root)
    candidates = _storage._rows(root / "lp_candidate_pairs.jsonl")
    requests = _storage._rows(root / "lp_generation_requests.jsonl")
    summary = json.loads((root / "lp_candidate_summary.json").read_bytes())
    receipt = json.loads((root / "lp_generation_checkpoint_manifest.json").read_bytes())
    material = receipt["material"]
    framework = harness.bundle.framework
    upstream = harness.bundle.model_dump(mode="json")
    for name, key in (
        ("items", "case_identifier_uuid"),
        ("learning_components", "identifier"),
        ("relationships_has_child", "identifier"),
        ("relationships_supports", "identifier"),
    ):
        upstream[name] = sorted(upstream[name], key=itemgetter(key))
    published = {
        (str(c.source_sfi_uuid), str(c.target_sfi_uuid), c.judgment.decision): c
        for c in final.claims
        if c.source_sfi_uuid is not None
    }
    edges = (*rows.relationships_builds_towards, *rows.relationships_relates_to)
    assert len(edges) == len(published) == len(rows.relationship_provenance)
    assert set(rows.relationship_provenance) == {str(edge.identifier) for edge in edges}
    assert rows.final_claims_content_hash == _claims._hash(
        final.model_dump(exclude={"content_hash"}, mode="json")
    )
    for edge in edges:
        claim = published[
            (edge.source_entity_value, edge.target_entity_value, edge.relationship_type)
        ]
        assert edge.source_entity == edge.target_entity == "StandardsFrameworkItem"
        assert (
            edge.source_entity_key == edge.target_entity_key == "case_identifier_uuid"
        )
        assert edge.source_entity_value != edge.target_entity_value
        endpoints = {str(item.case_identifier_uuid) for item in harness.bundle.items}
        assert {edge.source_entity_value, edge.target_entity_value} <= endpoints
        assert edge.author == "LLM generated"
        assert edge.provider == "IDinsight"
        assert edge.license == framework.license
        assert edge.attribution_statement == _TEMPLATE.replace(
            "{source_attribution_statement}", framework.attribution_statement
        )
        expected = {
            "approved_by": "IDinsight",
            "attribution_statement_template": _TEMPLATE,
            "candidate_artifact_byte_hashes": {
                name: hashlib.sha256((root / name).read_bytes()).hexdigest()
                for name in (
                    "lp_candidate_pairs.jsonl",
                    "lp_candidate_summary.json",
                    "lp_generation_requests.jsonl",
                )
            },
            "candidate_pairs_content_hash": _material_hash(candidates),
            "candidate_summary_content_hash": _material_hash(summary),
            "claim": claim.model_dump(mode="json"),
            "config_content_hash": _material_hash(
                harness.config.model_dump(by_alias=True, mode="json")
            ),
            "doc_key": _DOC_KEY,
            "effective_lp_config_content_hash": _claims._hash(
                harness.config.learning_progressions.model_dump(mode="json")
            ),
            "final_claims_content_hash": rows.final_claims_content_hash,
            "model_configuration": material["model_config"],
            "model_configuration_content_hash": _claims._hash(material["model_config"]),
            "model_settings": material["model_settings"],
            "model_settings_content_hash": _claims._hash(material["model_settings"]),
            "relationship_identity_key": (
                f"lc:curriculum:{_DOC_KEY}:relationship:{edge.relationship_type}:"
                f"{edge.source_entity_value}:{edge.target_entity_value}"
            ),
            "requests_content_hash": _material_hash(requests),
            "source_framework": {
                "attribution_statement": framework.attribution_statement,
                "author": framework.author,
                "case_identifier_uuid": str(framework.case_identifier_uuid),
                "license": framework.license,
                "provider": framework.provider,
                "title": framework.name,
            },
            "upstream_content_hash": _material_hash(upstream),
        }
        assert edge.metadata == expected
        assert (
            rows.relationship_provenance[str(edge.identifier)].model_dump(mode="json")
            == expected
        )
        assert claim.candidate.model_dump(mode="json") == next(
            c for c in candidates if c["pair_id"] == claim.judgment.pair_id
        )
        assert Relationship.model_validate_json(edge.model_dump_json()) == edge
    assert LPRelationships.model_validate_json(rows.model_dump_json()) == rows


