@pytest.mark.parametrize(
    argnames=("decision", "direction", "identifier"),
    argvalues=[
        ("buildsTowards", "first_to_second", "00249632-9338-52fc-932e-e82cdc7355f5"),
        ("buildsTowards", "second_to_first", "e897dc91-7e4c-575b-8082-468ff4df28a2"),
        ("relatesTo", None, "06d7c270-ce59-57ff-b098-cfa76e85d9a2"),
    ],
)
def test_uuid_snapshots_distinguish_semantic_direction_and_public_type(
    decision: str,
    direction: str | None,
    identifier: str,
    monkeypatch: pytest.MonkeyPatch,
    tmp_path: Path,
) -> None:
    """Identity uses resolved CASE endpoints and relation rather than candidate order.

    Parameters
    ----------
    decision
        Adjudicated public relationship type.
    direction
        Semantic direction independent of technical UUID ordering.
    identifier
        Independently pinned namespace-and-endpoint UUIDv5 value.
    monkeypatch
        Offline model seam.
    tmp_path
        Isolated persisted evidence.
    """
    harness = _claims._Harness(count=2, root=tmp_path)
    harness.decisions[(1, 2)] = (decision, direction)
    _claims._install(harness=harness, monkeypatch=monkeypatch)
    harness._run()
    harness._finalize()
    rows = _build(harness)
    edges = (*rows.relationships_builds_towards, *rows.relationships_relates_to)
    assert len(edges) == 1
    edge = edges[0]
    assert edge.identifier == UUID(identifier)
    assert edge.relationship_type == decision
    assert edge.source_entity_value == str(
        UUID(int=2 if direction == "second_to_first" else 1)
    )
    assert edge.target_entity_value == str(
        UUID(int=1 if direction == "second_to_first" else 2)
    )
    assert edge.metadata["claim"]["provenance"]["checker_outcome"] == "accepted"
    _assert_metadata(harness=harness, rows=rows)
