@pytest.mark.parametrize(argnames="empty", argvalues=[None, "", " \n "])
@pytest.mark.parametrize(
    argnames="relation",
    argvalues=["buildsTowards", "hasChild", "relatesTo", "supports"],
)
def test_default_descriptions_disclose_semantics_and_preserve_existing_types(
    empty: str | None, relation: str
) -> None:
    """Fallback descriptions state inference semantics while retaining AS/LC wording.

    Parameters
    ----------
    empty
        Missing or blank description requiring the generic fallback.
    relation
        Existing or newly minted public relationship type.
    """
    payload = {
        "attribution_statement": "Synthetic attribution",
        "author": "Synthetic author",
        "description": empty,
        "identifier": str(UUID(int=900)),
        "license": "Synthetic license",
        "provider": "Synthetic provider",
        "relationship_type": relation,
        "source_entity": (
            "LearningComponent" if relation == "supports" else "StandardsFrameworkItem"
        ),
        "source_entity_key": (
            "identifier" if relation == "supports" else "case_identifier_uuid"
        ),
        "source_entity_value": str(UUID(int=1)),
        "target_entity": "StandardsFrameworkItem",
        "target_entity_key": "case_identifier_uuid",
        "target_entity_value": str(UUID(int=2)),
    }
    description = Relationship.model_validate(payload).description
    if relation == "buildsTowards":
        assert "proficiency" in description and "likelihood of success" in description
        assert "does not assert a mandatory prerequisite" in description
        assert "prerequisite progression" not in description
    elif relation == "relatesTo":
        assert "conceptual or skill coherence" in description
        assert "without asserting sequence or dependency" in description
        assert "technical, not semantic" in description
    else:
        assert (
            description
            == {
                "hasChild": "A hasChild relationship links a parent framework/item to a child standards item.",
                "supports": "A supports relationship links a learning component to a standards item it supports.",
            }[relation]
        )
    payload["description"] = "Existing explicit relationship description."
    assert Relationship.model_validate(payload).description == payload["description"]


@pytest.mark.parametrize(argnames="batch", argvalues=[1, 3])
def test_direct_checker_selected_edges_have_pinned_ids_and_exact_provenance(
    batch: int, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    """Retain every direct accepted edge and both model outcomes without closure.

    Parameters
    ----------
    batch
        Distinct request boundaries around the same six pairs.
    monkeypatch
        Offline producer/checker seam.
    tmp_path
        Isolated persisted artifacts.
    """
    harness = _claims._Harness(batch=batch, root=tmp_path)
    harness.decisions = {
        (1, 2): ("buildsTowards", "second_to_first"),
        (1, 3): ("relatesTo", None),
        (1, 4): ("needs_review", None),
        (2, 3): ("buildsTowards", "first_to_second"),
        (2, 4): ("no_relation", None),
        (3, 4): ("relatesTo", None),
    }
    harness.corrections = {
        **harness.decisions,
        (1, 2): ("buildsTowards", "first_to_second"),
        (1, 3): ("buildsTowards", "first_to_second"),
    }
    harness.bundle.framework.author = "Synthetic source publisher"
    harness.bundle.framework.provider = "Synthetic source archive"
    harness.bundle.framework.license = "Synthetic license — A\n  B {literal}"
    harness.bundle.framework.attribution_statement = (
        "Synthetic éditeur\n  source {source_attribution_statement} {other}"
    )
    _claims._install(harness=harness, monkeypatch=monkeypatch)
    harness._run()
    final = harness._finalize()
    before = _storage._snapshot(tmp_path)
    source = harness.bundle.model_dump_json()
    calls = list(harness.calls)
    rows = _build(harness)
    assert {str(e.identifier) for e in rows.relationships_builds_towards} == {
        "00249632-9338-52fc-932e-e82cdc7355f5",
        "63f1854a-ebe5-5981-a097-23192667f375",
        "e2947c54-d7ae-5f50-a15b-3fbcf41a2ae5",
    }
    assert [str(e.identifier) for e in rows.relationships_relates_to] == [
        "0f78f128-4795-5cd0-9c20-c10034c4b4f0"
    ]
    assert final.decision_counts == {
        "buildsTowards": 3,
        "relatesTo": 1,
        "no_relation": 1,
        "needs_review": 1,
    }
    for edges in (rows.relationships_builds_towards, rows.relationships_relates_to):
        assert [str(e.identifier) for e in edges] == sorted(
            str(e.identifier) for e in edges
        )
    _assert_metadata(harness=harness, rows=rows)
    assert harness.bundle.model_dump_json() == source
    harness.bundle.items.reverse()
    harness.bundle.relationships_has_child.reverse()
    assert _build(harness).model_dump_json() == rows.model_dump_json()
    assert _storage._snapshot(tmp_path) == before
    assert harness.calls == calls


