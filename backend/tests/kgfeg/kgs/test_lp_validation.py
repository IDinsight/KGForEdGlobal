def _complete(
    *, harness: _claims._Harness, monkeypatch: pytest.MonkeyPatch
) -> tuple[LPFinalClaims, LPRelationships]:
    """Create a complete offline adjudication and its direct relationship rows.

    Parameters
    ----------
    harness
        Synthetic material and endpoint-keyed producer/checker script.
    monkeypatch
        Offline model seam.

    Returns
    -------
    tuple[LPFinalClaims, LPRelationships]
        Reconstructed final claims and exactly minted direct rows.
    """
    _claims._install(harness=harness, monkeypatch=monkeypatch)
    harness._run()
    final_claims = harness._finalize()
    relationships = build_lp_relationships(
        as_lc_bundle=harness.bundle,
        doc_key=_DOC_KEY,
        kg_config=harness.config,
        kg_dirs=KGDirs(root=harness.root),
    )
    return final_claims, relationships


def _cycle_relationships(
    *, artifact: LPFinalClaims, harness: _claims._Harness
) -> LPRelationships:
    """Build diagnostic input rows independently when public minting rejects cycles.

    Parameters
    ----------
    artifact
        Complete cyclic claim population written for diagnosis.
    harness
        Current source framework, config, and artifact directory.

    Returns
    -------
    LPRelationships
        Exact direct rows with embedded and separately keyed claim provenance.
    """
    framework = harness.bundle.framework
    policy = harness.config.learning_progressions.relationship_metadata
    model_configuration = artifact.execution_material["model_config"]
    model_settings = artifact.execution_material["model_settings"]
    edges: list[Relationship] = []
    provenance_by_id: dict[str, LPRelationshipProvenance] = {}

    for claim in artifact.claims:
        if claim.source_sfi_uuid is None or claim.target_sfi_uuid is None:
            continue

        source = str(claim.source_sfi_uuid)
        target = str(claim.target_sfi_uuid)
        relationship_type = claim.judgment.decision
        identity_key = (
            f"lc:curriculum:{_DOC_KEY}:relationship:{relationship_type}:"
            f"{source}:{target}"
        )
        identifier = uuid5(
            name=identity_key, namespace=Settings.LC_CANONICAL_NAMESPACE_UUID
        )
        provenance = LPRelationshipProvenance(
            approved_by=policy.approved_by,
            attribution_statement_template=policy.attribution_statement_template,
            candidate_artifact_byte_hashes=(
                artifact.request_manifest.artifact_byte_hashes
            ),
            candidate_pairs_content_hash=(
                artifact.request_manifest.candidate_pairs_content_hash
            ),
            candidate_summary_content_hash=(
                artifact.request_manifest.candidate_summary_content_hash
            ),
            claim=claim,
            config_content_hash=artifact.request_manifest.config_content_hash,
            doc_key=_DOC_KEY,
            effective_lp_config_content_hash=_hash(
                harness.config.learning_progressions.model_dump(mode="json")
            ),
            final_claims_content_hash=artifact.content_hash,
            model_configuration=model_configuration,
            model_configuration_content_hash=_hash(model_configuration),
            model_settings=model_settings,
            model_settings_content_hash=_hash(model_settings),
            relationship_identity_key=identity_key,
            requests_content_hash=artifact.request_manifest.requests_content_hash,
            source_framework={
                "attribution_statement": framework.attribution_statement,
                "author": framework.author,
                "case_identifier_uuid": framework.case_identifier_uuid,
                "license": framework.license,
                "provider": framework.provider,
                "title": framework.name,
            },
            upstream_content_hash=artifact.request_manifest.upstream_content_hash,
        )
        edge = Relationship(
            attribution_statement=_TEMPLATE.replace(
                "{source_attribution_statement}", framework.attribution_statement
            ),
            author="LLM generated",
            identifier=identifier,
            license=framework.license,
            metadata=provenance.model_dump(mode="json"),
            provider="IDinsight",
            relationship_type=relationship_type,
            source_entity="StandardsFrameworkItem",
            source_entity_key="case_identifier_uuid",
            source_entity_value=source,
            target_entity="StandardsFrameworkItem",
            target_entity_key="case_identifier_uuid",
            target_entity_value=target,
        )
        edges.append(edge)
        provenance_by_id[str(identifier)] = provenance

    edges.sort(key=lambda edge: str(edge.identifier))
    return LPRelationships(
        final_claims_content_hash=artifact.content_hash,
        relationship_provenance={
            str(edge.identifier): provenance_by_id[str(edge.identifier)]
            for edge in edges
        },
        relationships_builds_towards=tuple(
            edge for edge in edges if edge.relationship_type == "buildsTowards"
        ),
        relationships_relates_to=tuple(
            edge for edge in edges if edge.relationship_type == "relatesTo"
        ),
    )


def _hash(value: Any) -> str:
    """Hash canonical artifact material independently of production helpers.

    Parameters
    ----------
    value
        JSON-compatible material.

    Returns
    -------
    str
        SHA-256 of sorted compact Unicode JSON with its terminal newline.
    """
    return hashlib.sha256(_storage._bytes(value)).hexdigest()


def _report(
    *, harness: _claims._Harness, relationships: LPRelationships
) -> LPValidationReport:
    """Call the public standalone validator with current persisted material.

    Parameters
    ----------
    harness
        Current source bundle, configuration, and artifact directory.
    relationships
        Deterministically minted direct rows and separately keyed provenance.

    Returns
    -------
    LPValidationReport
        Structural/process verdict under test.
    """
    return validate_lp_graph(
        as_lc_bundle=harness.bundle,
        doc_key=_DOC_KEY,
        kg_config=harness.config,
        kg_dirs=KGDirs(root=harness.root),
        relationships=relationships,
    )


def _snapshot(root: Path) -> dict[str, bytes]:
    """Capture every regular file byte without interpreting generated evidence.

    Parameters
    ----------
    root
        Isolated generation directory.

    Returns
    -------
    dict[str, bytes]
        Relative filenames and exact bytes.
    """
    return {
        str(path.relative_to(root)): path.read_bytes()
        for path in sorted(root.rglob("*"))
        if path.is_file()
    }


