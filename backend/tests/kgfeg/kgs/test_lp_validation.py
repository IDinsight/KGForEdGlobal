@pytest.mark.parametrize(
    argnames="attack", argvalues=["failed_pair", "incomplete_stage", "status"]
)
def test_authenticated_incomplete_checkpoint_or_failure_blocks_success(
    attack: str, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    """Reject authenticated but unsuccessful checkpoint completion state.

    Parameters
    ----------
    attack
        Unresolved pair, incomplete successful prefix, or non-completed receipt state.
    monkeypatch
        Offline producer/checker seam and authenticated checkpoint-state injection.
    tmp_path
        Isolated persisted material.
    """
    harness = _claims._Harness(count=2, root=tmp_path)
    final_claims, relationships = _complete(harness=harness, monkeypatch=monkeypatch)
    receipt_path = tmp_path / "lp_generation_checkpoint_manifest.json"
    failure_path = tmp_path / _FAILURE
    receipt = json.loads(receipt_path.read_bytes())
    failures: list[dict[str, Any]] = []
    if attack == "failed_pair":
        failures = [
            {
                "pair_ids": [final_claims.request_manifest.pair_ids[0]],
                "resolved_run_number": None,
            }
        ]
    elif attack == "incomplete_stage":
        receipt["stage_counts"]["response"] -= 1
    else:
        receipt["status"] = "failed"
    failure_bytes = _storage._bytes(failures)
    failure_path.write_bytes(failure_bytes)
    receipt["artifact_byte_hashes"][_FAILURE] = hashlib.sha256(
        failure_bytes
    ).hexdigest()
    receipt_bytes = _storage._bytes(receipt)
    receipt_path.write_bytes(receipt_bytes)
    injected = final_claims.model_copy(
        deep=True,
        update={
            "checkpoint_receipt_byte_hash": hashlib.sha256(receipt_bytes).hexdigest()
        },
    )
    monkeypatch.setattr(
        name="validate_lp_final_claims_artifact",
        target=lp_validation,
        value=Mock(return_value=injected),
    )
    report = _report(harness=harness, relationships=relationships)
    assert not report.passed
    expected = {
        "failed_pair": "unresolved failed pairs",
        "incomplete_stage": "do not cover every request",
        "status": "not completed with zero failed pairs",
    }[attack]
    assert any(expected in error for error in report.errors)


