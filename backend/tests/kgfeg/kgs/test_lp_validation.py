def test_graph_shape_identity_duplicates_and_collisions_are_rejected(
    attack: str, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    """Reject malformed rows even when their generic relationship schema is valid.

    Parameters
    ----------
    attack
        Intrinsic row, identity, pair, endpoint, or graph collision mutation.
    monkeypatch
        Offline producer/checker seam.
    tmp_path
        Isolated persisted material.
    """
    harness = _claims._Harness(count=2, root=tmp_path)
    harness.default_decision = "relatesTo"
    _, relationships = _complete(harness=harness, monkeypatch=monkeypatch)
    edge = relationships.relationships_relates_to[0]
    rows = [edge]
    updates: dict[str, Any] = {}
    expected = ""
    if attack == "duplicate_id":
        rows.append(edge.model_copy(deep=True))
        expected = "identifiers are duplicated"
    elif attack == "identity":
        updates["identifier"] = UUID(int=700)
        expected = "complete directly accepted claim population"
    elif attack == "noncanonical_relates_to":
        updates.update(
            source_entity_value=edge.target_entity_value,
            target_entity_value=edge.source_entity_value,
        )
        expected = "not in canonical endpoint order"
    elif attack == "self_loop":
        updates["target_entity_value"] = edge.source_entity_value
        expected = "self-loop"
    elif attack == "unknown_endpoint":
        updates["target_entity_value"] = str(UUID(int=999))
        expected = "unknown SFI endpoint"
    elif attack == "unsupported_relation":
        updates["relationship_type"] = "recurring_practice"
        expected = "differs from its deterministic identity"
    elif attack == "wrong_endpoint_key":
        updates["source_entity_key"] = "identifier"
        expected = "differs from its deterministic identity"
    else:
        updates["source_entity"] = "LearningComponent"
        expected = "differs from its deterministic identity"
    rows[0] = edge.model_copy(deep=True, update=updates)
    attacked = relationships.model_copy(
        deep=True, update={"relationships_relates_to": tuple(rows)}
    )
    if attack in {
        "self_loop",
        "unsupported_relation",
        "wrong_endpoint_key",
        "wrong_entity_type",
    }:
        expected_schema_error = {
            "self_loop": "cannot connect an entity to itself",
            "unsupported_relation": "Unsupported relationshipType",
            "wrong_endpoint_key": "must use case_identifier_uuid endpoints",
            "wrong_entity_type": (
                "must be StandardsFrameworkItem -> StandardsFrameworkItem"
            ),
        }[attack]
        with pytest.raises(ValueError, match=expected_schema_error):
            _report(harness=harness, relationships=attacked)
        return
    report = _report(harness=harness, relationships=attacked)
    assert not report.passed
    assert any(expected in error for error in report.errors)


