def _validate_bcp47(code: str) -> str:
    """Validates that a string is a valid BCP-47 language tag.

    Parameters
    ----------
    code
        The language tag to validate.

    Returns
    -------
    str
        The standardized version (e.g., 'en_us' -> 'en-US').

    Raises
    ------
    ValueError
        If the language tag is invalid or unparseable.
    """

    code = (code or "und").strip().replace("_", "-")

    if code in {"und", "mul"}:
        return code

    try:
        lang = langcodes.Language.get(code)

        if not lang.is_valid():
            raise ValueError(f"Invalid BCP-47 language tag: '{code}'")

        return lang.to_tag()
    except langcodes.LanguageTagError as exc:
        raise ValueError(f"Unparseable language tag: '{code}'") from exc


def _validate_lp_attribution_statement_template(value: str) -> str:
    """Validate the approved LP relationship attribution template.

    Parameters
    ----------
    value
        Attribution template supplied by one curriculum profile.

    Returns
    -------
    str
        The stripped approved attribution template.

    Raises
    ------
    ValueError
        If the template differs from the approved inference disclosure.
    """

    template = strip_and_require_non_empty_str(value)
    approved_template = (
        "Learning progression relationship generated by IDinsight using an LLM "
        "producer/checker workflow. Source framework attribution: "
        "{source_attribution_statement}. This inferred relationship was not stated "
        "or endorsed by the source publisher."
    )

    if template != approved_template:
        raise ValueError(
            "Learning Progressions attribution_statement_template must match the "
            "approved inference-disclosing template exactly."
        )

    return template


def _validate_lp_non_empty_unique_strings(values: list[str]) -> list[str]:
    """Validate and clean an ordered LP configuration string list.

    Parameters
    ----------
    values
        Ordered strings supplied by one intrinsic LP policy field.

    Returns
    -------
    list[str]
        Stripped strings in their configured order.

    Raises
    ------
    ValueError
        If the list is empty or two values have the same normalized key.
    """

    if not values:
        raise ValueError("Learning Progressions policy lists must not be empty.")

    cleaned: list[str] = []
    seen: set[str] = set()

    for value in values:
        item = strip_and_require_non_empty_str(value)
        normalized_item = normalize_controlled_value_key(item)

        if normalized_item in seen:
            raise ValueError(
                f"Learning Progressions policy lists must not contain duplicate "
                f"values: {item!r}."
            )

        cleaned.append(item)
        seen.add(normalized_item)

    return cleaned


def normalize_controlled_value_key(value: str) -> str:
    """Build a Unicode-aware comparison key for controlled values and aliases.

    The normalization preserves Unicode letters and numbers while collapsing
    punctuation, symbols, and whitespace into single spaces. NFKC normalization makes
    compatibility forms comparable without transliterating or discarding
    source-language characters.

    Parameters
    ----------
    value
        Controlled value, alias, statement type, or other source-facing label.

    Returns
    -------
    str
        NFKC-normalized, casefolded key containing Unicode letters, numbers, and
        combining marks.
    """

    normalized = unicodedata.normalize("NFKC", str(value or "")).casefold()
    letters_numbers_marks_or_spaces = "".join(
        (
            character
            if character.isalnum() or unicodedata.category(character).startswith("M")
            else " "
        )
        for character in normalized
    )
    return " ".join(letters_numbers_marks_or_spaces.split())


def validate_bbox_order(bbox: list[float]) -> list[float]:
    """Ensure bbox is well-ordered: [x0, y0, x1, y1] with x0 < x1 and y0 < y1.

    Parameters
    ----------
    bbox
        The bounding box to validate.

    Returns
    -------
    list[float]
        The validated bounding box.

    Raises
    ------
    ValueError
        If the bounding box does not have exactly 4 numbers.
    """

    if len(bbox) != 4:
        raise ValueError(
            f"Bounding box must have exactly 4 numbers: [x0, y0, x1, y1]. Got: {bbox}"
        )

    x0, y0, x1, y1 = bbox

    # Auto-correct inverted or zero-dimension axes. For equal dimensions, add 1 pixel.
    if x0 >= x1:
        if x0 > x1:
            x0, x1 = x1, x0
        else:
            x1 = x0 + 1.0
    if y0 >= y1:
        if y0 > y1:
            y0, y1 = y1, y0
        else:
            y1 = y0 + 1.0

    return [x0, y0, x1, y1]


